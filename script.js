// Funcionalidades de Abas de Classificações e Filtros (Setúbal Challenge)
// ============================================================
function inicializarTabsClassificacoes() {
    const tabBotoes = document.querySelectorAll('.tab-btn[data-tab-ano]');
    const paineisAno = document.querySelectorAll('.painel-ano');

    if (!tabBotoes.length || !paineisAno.length) return;

    function ativarAbaAno(ano) {
        // Atualiza os botões
        tabBotoes.forEach(btn => {
            const btnAno = btn.getAttribute('data-tab-ano');
            const isAtivo = btnAno === ano;
            if (isAtivo) {
                btn.classList.add('ativo');
                btn.setAttribute('aria-selected', 'true');
                btn.setAttribute('tabindex', '0');
            } else {
                btn.classList.remove('ativo');
                btn.setAttribute('aria-selected', 'false');
                btn.setAttribute('tabindex', '-1');
            }
        });

        // Atualiza os painéis
        paineisAno.forEach(painel => {
            const painelId = painel.id;
            if (painelId === `painel-classificacao-${ano}`) {
                painel.style.display = 'block';
                painel.classList.add('ativo');
            } else {
                painel.style.display = 'none';
                painel.classList.remove('ativo');
            }
        });
    }

    tabBotoes.forEach((btn, index) => {
        btn.addEventListener('click', () => {
            const ano = btn.getAttribute('data-tab-ano');
            if (ano) ativarAbaAno(ano);
        });

        // Acessibilidade via teclado (setas esquerda/direita)
        btn.addEventListener('keydown', (e) => {
            let nextIndex = index;
            if (e.key === 'ArrowRight') {
                nextIndex = (index + 1) % tabBotoes.length;
            } else if (e.key === 'ArrowLeft') {
                nextIndex = (index - 1 + tabBotoes.length) % tabBotoes.length;
            } else {
                return;
            }
            e.preventDefault();
            tabBotoes[nextIndex].focus();
            const ano = tabBotoes[nextIndex].getAttribute('data-tab-ano');
            if (ano) ativarAbaAno(ano);
        });
    });

    // Filtros de categoria para o ano de 2026
    const filtroBotoes = document.querySelectorAll('.cat-filtro-btn[data-filtro]');
    const painel2026 = document.getElementById('painel-classificacao-2026');

    if (filtroBotoes.length && painel2026) {
        filtroBotoes.forEach(btn => {
            btn.addEventListener('click', () => {
                const filtro = btn.getAttribute('data-filtro');

                // Atualiza classe ativa dos botões de filtro
                filtroBotoes.forEach(b => b.classList.toggle('ativo', b === btn));

                const blocosDia = painel2026.querySelectorAll('.bloco-dia');
                const cards = painel2026.querySelectorAll('.categoria-card');

                if (filtro === 'todos') {
                    blocosDia.forEach(bloco => bloco.classList.remove('oculto'));
                    cards.forEach(card => card.classList.remove('oculto'));
                } else {
                    cards.forEach(card => {
                        const cat = card.getAttribute('data-categoria');
                        if (cat === filtro) {
                            card.classList.remove('oculto');
                        } else {
                            card.classList.add('oculto');
                        }
                    });

                    // Oculta blocos de dias caso todos os seus cards estejam ocultos
                    blocosDia.forEach(bloco => {
                        const cardsVisiveis = bloco.querySelectorAll('.categoria-card:not(.oculto)');
                        if (cardsVisiveis.length === 0) {
                            bloco.classList.add('oculto');
                        } else {
                            bloco.classList.remove('oculto');
                        }
                    });
                }
            });
        });
    }
}

