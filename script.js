// Obtém o idioma atual salvo no localStorage ou detecta pelo navegador
function obterIdiomaAtual() {
    const salvo = localStorage.getItem('kahu_idioma');
    if (salvo && (salvo === 'pt' || salvo === 'en' || salvo === 'fr')) {
        return salvo;
    }
    const navLang = (navigator.language || navigator.userLanguage || 'pt').toLowerCase();
    if (navLang.startsWith('fr')) return 'fr';
    if (navLang.startsWith('en')) return 'en';
    return 'pt';
}

// Aplica o idioma escolhido a todos os elementos da página
function aplicarIdioma(lang) {
    const idioma = (lang === 'pt' || lang === 'en' || lang === 'fr') ? lang : 'pt';
    localStorage.setItem('kahu_idioma', idioma);

    const t = traducoes[idioma] || traducoes.pt;

    // Atualiza o atributo lang na tag <html>
    document.documentElement.lang = t.lang_code || idioma;

    // Atualiza o título da página
    const urlAtual = window.location.pathname.split('/').pop().toLowerCase();
    if (urlAtual === 'setubal-challenge.html' || urlAtual === 'sobre.html') {
        document.title = t.titulo_setubal;
    } else if (urlAtual === 'participe.html' || urlAtual === 'contato.html') {
        document.title = t.titulo_participe;
    } else {
        document.title = t.titulo_index;
    }

    // Atualiza elementos com data-i18n (texto puro)
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) {
            el.textContent = t[key];
        }
    });

    // Atualiza elementos com data-i18n-html (contém tags como <span>, <strong>)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (t[key] !== undefined) {
            el.innerHTML = t[key];
        }
    });

    // Atualiza placeholders em inputs e textareas
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key] !== undefined) {
            el.setAttribute('placeholder', t[key]);
        }
    });

    // Atualiza tooltips e títulos
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (t[key] !== undefined) {
            el.setAttribute('title', t[key]);
        }
    });

    // Atualiza aria-labels
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (t[key] !== undefined) {
            el.setAttribute('aria-label', t[key]);
        }
    });

    // Atualiza botões de controle de vídeo e áudio se presentes
    const btnToggleVideo = document.getElementById('btn-toggle-video');
    const video = document.getElementById('video-destaque');
    if (btnToggleVideo && video) {
        const videoLabel = video.paused ? t.btn_video_play : t.btn_video_pause;
        btnToggleVideo.setAttribute('aria-label', videoLabel);
        btnToggleVideo.setAttribute('title', videoLabel);
    }

    const btnToggleSom = document.getElementById('btn-toggle-som');
    if (btnToggleSom && video) {
        const audioLabel = video.muted ? t.btn_audio_unmute : t.btn_audio_mute;
        btnToggleSom.setAttribute('aria-label', audioLabel);
        btnToggleSom.setAttribute('title', audioLabel);
    }

    // Atualiza estado ativo dos botões seletores de idioma
    document.querySelectorAll('.btn-idioma').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === idioma) {
            btn.classList.add('ativo');
            btn.setAttribute('aria-pressed', 'true');
        } else {
            btn.classList.remove('ativo');
            btn.setAttribute('aria-pressed', 'false');
        }
    });

    // Dispara evento customizado caso outros módulos precisem saber da mudança
    window.dispatchEvent(new CustomEvent('idiomaAlterado', { detail: { idioma } }));
}

// Cria e insere o cabeçalho fixo na página
function carregarMenu() {
    let header = document.getElementById('cabecalho');

    const urlAtual = window.location.pathname.split('/').pop().toLowerCase();
    let paginaAtual = (urlAtual === '' || urlAtual === '/' || urlAtual === 'index.html') ? 'index.html' : urlAtual;
    
    // Suporte a compatibilidade de rotas
    if (paginaAtual === 'sobre.html') paginaAtual = 'setubal-challenge.html';
    if (paginaAtual === 'contato.html') paginaAtual = 'participe.html';

    const idiomaAtual = obterIdiomaAtual();

    if (!header) {
        const menuTemplate = `
            <header class="cabecalho-fixo" id="cabecalho">
                <div class="nav-container">
                    <a href="index.html" class="logo">
                        <img src="assets/BRANCO_LOGO.webp" alt="Logo Kahu Moana" class="logo-img">
                    </a>

                    <div class="nav-acoes">
                        <nav class="nav-links" id="nav-links" aria-label="Navegação principal">
                            <ul> 
                                ${itensMenu.map(item => {
                                    const isAtivo = paginaAtual === item.link.toLowerCase();
                                    return `
                                        <li>
                                            <a href="${item.link}" class="${isAtivo ? 'ativo' : ''}">
                                                <i class="${item.icone}"></i>
                                                <span data-i18n="${item.key}">${traducoes[idiomaAtual][item.key]}</span>
                                            </a>
                                        </li>
                                    `;
                                }).join('')}
                            </ul>

                            <!-- Seletor no Menu Mobile -->
                            <div class="seletor-idioma-mobile">
                                <span class="seletor-idioma-mobile-label">
                                    <i class="fa-solid fa-globe"></i>
                                    <span data-i18n="seletor_idioma_label">${traducoes[idiomaAtual].seletor_idioma_label}</span>
                                </span>
                                <div class="seletor-idioma" role="group" aria-label="Idioma">
                                    <button type="button" class="btn-idioma ${idiomaAtual === 'pt' ? 'ativo' : ''}" data-lang="pt" title="Português">PT</button>
                                    <button type="button" class="btn-idioma ${idiomaAtual === 'en' ? 'ativo' : ''}" data-lang="en" title="English">EN</button>
                                    <button type="button" class="btn-idioma ${idiomaAtual === 'fr' ? 'ativo' : ''}" data-lang="fr" title="Français">FR</button>
                                </div>
                            </div>
                        </nav>

                        <!-- Seletor Desktop -->
                        <div class="seletor-idioma seletor-idioma-desktop" id="seletor-idioma-desktop" role="group" aria-label="Selecionar idioma">
                            <button type="button" class="btn-idioma ${idiomaAtual === 'pt' ? 'ativo' : ''}" data-lang="pt" title="Português">PT</button>
                            <button type="button" class="btn-idioma ${idiomaAtual === 'en' ? 'ativo' : ''}" data-lang="en" title="English">EN</button>
                            <button type="button" class="btn-idioma ${idiomaAtual === 'fr' ? 'ativo' : ''}" data-lang="fr" title="Français">FR</button>
                        </div>

                        <button class="btn-mobile" id="btn-mobile" aria-label="Abrir menu de navegação" aria-expanded="false">
                            <i class="fa-solid fa-bars"></i>
                        </button>
                    </div>
                </div>
                <div class="nav-overlay" id="nav-overlay"></div>
            </header>
        `;

        document.body.insertAdjacentHTML('afterbegin', menuTemplate);
        header = document.getElementById('cabecalho');
    }

    // Configura links ativos
    document.querySelectorAll('#nav-links ul li a').forEach(link => {
        const href = link.getAttribute('href') ? link.getAttribute('href').toLowerCase() : '';
        if (href === paginaAtual) {
            link.classList.add('ativo');
        } else {
            link.classList.remove('ativo');
        }
    });

    const btnMobile = document.getElementById('btn-mobile');
    const navLinks = document.getElementById('nav-links');
    const navOverlay = document.getElementById('nav-overlay');
    const iconeMobile = btnMobile ? btnMobile.querySelector('i') : null;
    const links = navLinks ? navLinks.querySelectorAll('a') : [];

    function abrirMenu() {
        if (!navLinks || !navOverlay || !btnMobile) return;
        navLinks.classList.add('ativo');
        navOverlay.classList.add('ativo');
        btnMobile.setAttribute('aria-expanded', 'true');
        btnMobile.setAttribute('aria-label', 'Fechar menu de navegação');
        document.body.style.overflow = 'hidden';

        if (iconeMobile) {
            iconeMobile.classList.remove('fa-bars');
            iconeMobile.classList.add('fa-xmark');
        }
    }

    function fecharMenu() {
        if (!navLinks || !navOverlay || !btnMobile) return;
        navLinks.classList.remove('ativo');
        navOverlay.classList.remove('ativo');
        btnMobile.setAttribute('aria-expanded', 'false');
        btnMobile.setAttribute('aria-label', 'Abrir menu de navegação');
        document.body.style.overflow = '';

        if (iconeMobile) {
            iconeMobile.classList.remove('fa-xmark');
            iconeMobile.classList.add('fa-bars');
        }
    }

    function alternarMenuMobile() {
        if (navLinks && navLinks.classList.contains('ativo')) {
            fecharMenu();
        } else {
            abrirMenu();
        }
    }

    if (btnMobile) {
        btnMobile.onclick = alternarMenuMobile;
    }

    if (navOverlay) {
        navOverlay.onclick = fecharMenu;
    }

    links.forEach(link => {
        link.onclick = fecharMenu;
    });

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && navLinks && navLinks.classList.contains('ativo')) {
            fecharMenu();
        }
    });

    window.addEventListener('scroll', () => {
        if (!header) return;
        if (window.scrollY > 20) {
            header.classList.add('rolando');
        } else {
            header.classList.remove('rolando');
        }
    });

    // Eventos de clique nos botões de idioma
    document.querySelectorAll('.btn-idioma').forEach(btn => {
        btn.onclick = () => {
            const lang = btn.getAttribute('data-lang');
            aplicarIdioma(lang);
        };
    });
}

