// Funcionalidades Interativas do Hero com Vídeo
// ============================================================
function inicializarHeroVideo() {
    const video = document.getElementById('video-destaque');
    const btnToggleVideo = document.getElementById('btn-toggle-video');
    const btnToggleSom = document.getElementById('btn-toggle-som');

    if (!video) return;

    const prefereReducaoMovimento = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if (prefereReducaoMovimento) {
        video.pause();
        if (btnToggleVideo) {
            btnToggleVideo.innerHTML = '<i class="fa-solid fa-play"></i>';
        }
    }

    if (btnToggleVideo) {
        btnToggleVideo.addEventListener('click', () => {
            const idioma = obterIdiomaAtual();
            const t = traducoes[idioma] || traducoes.pt;
            if (video.paused) {
                video.play().then(() => {
                    btnToggleVideo.innerHTML = '<i class="fa-solid fa-pause"></i>';
                    btnToggleVideo.setAttribute('aria-label', t.btn_video_pause);
                    btnToggleVideo.setAttribute('title', t.btn_video_pause);
                }).catch(() => {});
            } else {
                video.pause();
                btnToggleVideo.innerHTML = '<i class="fa-solid fa-play"></i>';
                btnToggleVideo.setAttribute('aria-label', t.btn_video_play);
                btnToggleVideo.setAttribute('title', t.btn_video_play);
            }
        });
    }

    if (btnToggleSom) {
        btnToggleSom.addEventListener('click', () => {
            const idioma = obterIdiomaAtual();
            const t = traducoes[idioma] || traducoes.pt;
            if (video.muted) {
                video.muted = false;
                btnToggleSom.innerHTML = '<i class="fa-solid fa-volume-high"></i>';
                btnToggleSom.setAttribute('aria-label', t.btn_audio_mute);
                btnToggleSom.setAttribute('title', t.btn_audio_mute);
            } else {
                video.muted = true;
                btnToggleSom.innerHTML = '<i class="fa-solid fa-volume-xmark"></i>';
                btnToggleSom.setAttribute('aria-label', t.btn_audio_unmute);
                btnToggleSom.setAttribute('title', t.btn_audio_unmute);
            }
        });
    }
}

